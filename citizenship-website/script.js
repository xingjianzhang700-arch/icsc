// ---------- Apply translations ----------
function applyLang(lang) {
  const dict = I18N[lang] || I18N.en;
  document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll(".lang-switch button").forEach(b => {
    b.classList.toggle("active", b.dataset.lang === lang);
  });
  try { localStorage.setItem("icsc_lang", lang); } catch {}
}

document.querySelectorAll(".lang-switch button").forEach(btn => {
  btn.addEventListener("click", () => applyLang(btn.dataset.lang));
});

// Restore saved language, else auto-detect from browser
(() => {
  let saved = null;
  try { saved = localStorage.getItem("icsc_lang"); } catch {}
  if (saved && I18N[saved]) return applyLang(saved);
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("es")) applyLang("es");
  else if (nav.startsWith("zh")) applyLang("zh");
  else applyLang("en");
})();

// ---------- N/A toggle behavior ----------
document.querySelectorAll('input[data-na-for]').forEach(cb => {
  cb.addEventListener("change", () => {
    const targetId = cb.getAttribute("data-na-for");
    const field = document.getElementById(targetId);
    if (!field) return;
    if (cb.checked) {
      field.dataset.prev = field.value;
      field.value = "N/A";
      field.disabled = true;
    } else {
      field.disabled = false;
      field.value = field.dataset.prev || "";
    }
  });
});

// ---------- Skip-schedule toggle: disable all day/time checkboxes ----------
(() => {
  const skip = document.getElementById("skip_schedule");
  if (!skip) return;
  const groups = ["sched_days", "sched_weekday", "sched_weekend"]
    .map(id => document.getElementById(id))
    .filter(Boolean);
  skip.addEventListener("change", () => {
    const off = skip.checked;
    groups.forEach(g => {
      g.classList.toggle("is-disabled", off);
      g.querySelectorAll("input[type=checkbox]").forEach(cb => {
        if (off) {
          cb.dataset.prevChecked = cb.checked ? "1" : "";
          cb.checked = false;
          cb.disabled = true;
        } else {
          cb.disabled = false;
          if (cb.dataset.prevChecked === "1") cb.checked = true;
        }
      });
    });
  });
})();

